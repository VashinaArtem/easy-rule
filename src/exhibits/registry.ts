export const openExhibits = exhibits.filter((e): e is OpenExhibit => e.status === 'open');

export function getHall(id: string | undefined): Hall | undefined {
  return halls.find((h) => h.id === id);
}

export function getOpenExhibit(id: string | undefined): OpenExhibit | undefined {
  return openExhibits.find((e) => e.id === id);
}

export function exhibitsInHall(hall: HallId): Exhibit[] {
  return exhibits.filter((e) => e.hall === hall);
}

/** Neighbours along the exhibition route (all open works, in hall order). */
export function neighbours(id: string): { prev?: OpenExhibit; next?: OpenExhibit } {
  const i = openExhibits.findIndex((e) => e.id === id);
  return { prev: openExhibits[i - 1], next: openExhibits[i + 1] };
}
